# Backups from the old scripts (backupDB.sh, and dbCycle.sh used by the old upgrade) are INSERTs
# without column names, which only restore into tables with the old column order. Name the columns.
name_legacy_columns() {
  sed \
      -e 's/^INSERT INTO Driver VALUES(/INSERT INTO Driver (id,name,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO Location VALUES(/INSERT INTO Location (id,name,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO Car VALUES(/INSERT INTO Car (id,name,driverId,defaultCarNumber,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO Session VALUES(/INSERT INTO Session (id,date,driverId,carId,driverName,carName,totalTime,totalLaps,notes,createdAt,updatedAt,locationId,locationName) VALUES(/' \
      -e 's/^INSERT INTO Lap VALUES(/INSERT INTO Lap (id,sessionId,lapNumber,lapTime,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO Penalty VALUES(/INSERT INTO Penalty (id,sessionId,lapNumber,count,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO MotionSettings VALUES(/INSERT INTO MotionSettings (id,name,sensitivity,threshold,cooldown,framesToSkip,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO SessionRequest VALUES(/INSERT INTO SessionRequest (id,driverId,carId,locationId,numberOfLaps,status,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO CurrentSession VALUES(/INSERT INTO CurrentSession (id,driverName,carName,locationName,lapCount,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO CurrentLap VALUES(/INSERT INTO CurrentLap (id,sessionId,lapTime,lapNumber,penaltyCount,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO Race VALUES(/INSERT INTO Race (id,name,date,locationId,status,startDelay,totalLaps,startTime,endTime,notes,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO RaceEntry VALUES(/INSERT INTO RaceEntry (id,raceId,driverId,carId,carNumber,position,lapsCompleted,bestLapTime,totalTime,status,dnfReason,createdAt,updatedAt) VALUES(/' \
      -e 's/^INSERT INTO RaceLap VALUES(/INSERT INTO RaceLap (id,raceEntryId,lapNumber,lapTime,position,gap,timestamp,createdAt,updatedAt) VALUES(/'
}

# dbCycle.sh ran mysql without -r, so the client escaped every backslash, newline and tab a second
# time (an apostrophe in session notes then breaks the INSERT). Undo that extra escaping.
undo_mysql_batch_escaping() {
  sed -e 's/\\\\/\x01/g' -e 's/\\n/\n/g' -e 's/\\t/\t/g' -e 's/\x01/\\/g'
}

# dbCycle.sh output starts with a blank header line; backupDB.sh (mysql -N -r) output doesn't.
convert_legacy_backup() {
  if [ -z "$(head -n 1 "$1")" ]; then
    undo_mysql_batch_escaping < "$1" | name_legacy_columns
  else
    name_legacy_columns < "$1"
  fi
}

# Usage: ./restoreDB.sh [backup.sql]   (defaults to the newest file in ~/db-backups)
# Older backups made by the previous upgrade script (~/backup_data.sql) can be passed explicitly.
backup_file="${1:-$(ls -1t ~/db-backups/rc_lap_timer.*.sql 2> /dev/null | head -n 1 || true)}"
if [ -z "$backup_file" ] || [ ! -f "$backup_file" ]; then
  echo "No backup found. Usage: ./restoreDB.sh [path/to/backup.sql]"
  exit 1
fi
if [ ! -s "$backup_file" ]; then
  echo "$backup_file is empty, so there is nothing to restore."
  exit 1
fi
echo "*** Restoring database from $backup_file"
read -r -p "This overwrites the current data. Type restore to continue: " answer || true
if [ "${answer:-}" != "restore" ]; then
  echo "Cancelled."
  exit 1
fi
sudo systemctl stop rc-lap-timer || true
# Start the app again however the restore ends.
trap 'sudo systemctl start rc-lap-timer || true' EXIT
if head -n 5 "$backup_file" | grep -qE '^-- (MySQL|MariaDB) dump'; then
  if ! mysql -u root -p rc_lap_timer < "$backup_file"; then
    echo "*** Restore failed (see the error above). If some tables were already replaced, run the restore again."
    exit 1
  fi
else
  echo "*** Old-format backup: converting it first. Rows that can't be restored (for example, ones that already exist) are reported and skipped."
  if ! { echo "SET FOREIGN_KEY_CHECKS=0;"; convert_legacy_backup "$backup_file"; echo "SET FOREIGN_KEY_CHECKS=1;"; } | mysql --force -u root -p rc_lap_timer; then
    echo "*** MySQL reported errors (see above). Rows without errors were restored; if the password was wrong, run the restore again."
    exit 1
  fi
fi
echo "*** Restore complete"

